-- SnapClass / AttendAI Supabase schema repair script.
-- Run this once in Supabase Dashboard > SQL Editor.
--
-- It creates any missing tables/columns used by the Streamlit app, repairs
-- common missing defaults, refreshes PostgREST's schema cache, and disables
-- RLS for demo/student-project usage.

create table if not exists public.teachers (
    teacher_id bigint generated by default as identity primary key,
    username text not null unique,
    password text not null,
    name text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.students (
    student_id bigint generated by default as identity primary key,
    name text not null,
    face_embedding jsonb,
    voice_embedding jsonb,
    created_at timestamptz not null default now()
);

create table if not exists public.subjects (
    subject_id bigint generated by default as identity primary key,
    subject_code text not null unique,
    name text not null,
    section text not null,
    teacher_id bigint not null references public.teachers(teacher_id) on delete cascade,
    created_at timestamptz not null default now()
);

create table if not exists public.subject_students (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(student_id) on delete cascade,
    subject_id bigint not null references public.subjects(subject_id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (student_id, subject_id)
);

create table if not exists public.attendance_logs (
    attendance_id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(student_id) on delete cascade,
    subject_id bigint not null references public.subjects(subject_id) on delete cascade,
    "timestamp" timestamptz not null default now(),
    is_present boolean not null default false,
    created_at timestamptz not null default now()
);

alter table public.teachers
    add column if not exists teacher_id bigint,
    add column if not exists username text,
    add column if not exists password text,
    add column if not exists name text,
    add column if not exists created_at timestamptz not null default now();

alter table public.students
    add column if not exists student_id bigint,
    add column if not exists name text,
    add column if not exists face_embedding jsonb,
    add column if not exists voice_embedding jsonb,
    add column if not exists created_at timestamptz not null default now();

alter table public.subjects
    add column if not exists subject_id bigint,
    add column if not exists subject_code text,
    add column if not exists name text,
    add column if not exists section text,
    add column if not exists teacher_id bigint,
    add column if not exists created_at timestamptz not null default now();

alter table public.subject_students
    add column if not exists id bigint,
    add column if not exists student_id bigint,
    add column if not exists subject_id bigint,
    add column if not exists created_at timestamptz not null default now();

alter table public.attendance_logs
    add column if not exists attendance_id bigint,
    add column if not exists student_id bigint,
    add column if not exists subject_id bigint,
    add column if not exists "timestamp" timestamptz not null default now(),
    add column if not exists is_present boolean not null default false,
    add column if not exists created_at timestamptz not null default now();

update public.teachers
set
    username = coalesce(username, 'teacher_' || teacher_id::text),
    password = coalesce(password, ''),
    name = coalesce(name, 'Teacher')
where username is null
   or password is null
   or name is null;

update public.students
set name = coalesce(name, 'Student')
where name is null;

update public.subjects
set
    subject_code = coalesce(subject_code, 'SUBJECT_' || subject_id::text),
    name = coalesce(name, 'Subject'),
    section = coalesce(section, 'A')
where subject_code is null
   or name is null
   or section is null;

update public.attendance_logs
set
    "timestamp" = coalesce("timestamp", now()),
    is_present = coalesce(is_present, false)
where "timestamp" is null
   or is_present is null;

-- Repair identity defaults when a table/column already existed but had no
-- auto-generated ID default. Each block is isolated so one existing default
-- does not stop the rest of the repair script.
do $$
begin
    begin
        alter table public.teachers alter column teacher_id add generated by default as identity;
    exception
        when others then null;
    end;

    begin
        alter table public.students alter column student_id add generated by default as identity;
    exception
        when others then null;
    end;

    begin
        alter table public.subjects alter column subject_id add generated by default as identity;
    exception
        when others then null;
    end;

    begin
        alter table public.subject_students alter column id add generated by default as identity;
    exception
        when others then null;
    end;

    begin
        alter table public.attendance_logs alter column attendance_id add generated by default as identity;
    exception
        when others then null;
    end;
end $$;

-- Make required app columns non-null where safe for future rows.
alter table public.teachers
    alter column username set not null,
    alter column password set not null,
    alter column name set not null;

alter table public.students
    alter column name set not null;

alter table public.subjects
    alter column subject_code set not null,
    alter column name set not null,
    alter column section set not null,
    alter column teacher_id set not null;

alter table public.subject_students
    alter column student_id set not null,
    alter column subject_id set not null;

alter table public.attendance_logs
    alter column student_id set not null,
    alter column subject_id set not null,
    alter column "timestamp" set not null,
    alter column is_present set not null,
    alter column is_present set default false;

-- Add primary keys and foreign keys required by Supabase nested selects.
do $$
begin
    begin
        alter table public.teachers add constraint teachers_pkey primary key (teacher_id);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.students add constraint students_pkey primary key (student_id);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.subjects add constraint subjects_pkey primary key (subject_id);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.subject_students add constraint subject_students_pkey primary key (id);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.attendance_logs add constraint attendance_logs_pkey primary key (attendance_id);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.subjects
        add constraint subjects_teacher_id_fkey
        foreign key (teacher_id) references public.teachers(teacher_id) on delete cascade;
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.subject_students
        add constraint subject_students_student_id_fkey
        foreign key (student_id) references public.students(student_id) on delete cascade;
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.subject_students
        add constraint subject_students_subject_id_fkey
        foreign key (subject_id) references public.subjects(subject_id) on delete cascade;
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.attendance_logs
        add constraint attendance_logs_student_id_fkey
        foreign key (student_id) references public.students(student_id) on delete cascade;
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.attendance_logs
        add constraint attendance_logs_subject_id_fkey
        foreign key (subject_id) references public.subjects(subject_id) on delete cascade;
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.teachers add constraint teachers_username_key unique (username);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.subjects add constraint subjects_subject_code_key unique (subject_code);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;

    begin
        alter table public.subject_students
        add constraint subject_students_student_id_subject_id_key unique (student_id, subject_id);
    exception
        when duplicate_object or invalid_table_definition then null;
    end;
end $$;

-- Demo mode: the app uses the public anon Supabase key and does not use
-- Supabase Auth, so RLS must be disabled unless you later add proper policies.
alter table public.teachers disable row level security;
alter table public.students disable row level security;
alter table public.subjects disable row level security;
alter table public.subject_students disable row level security;
alter table public.attendance_logs disable row level security;

-- Ask Supabase/PostgREST to refresh its schema cache immediately.
notify pgrst, 'reload schema';
